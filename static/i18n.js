document.addEventListener("DOMContentLoaded", () => {
    // Sync dropdowns
    const savedLang = localStorage.getItem("siteLang") || "en";
    document.querySelectorAll('.lang-selector').forEach(sel => {
        sel.value = savedLang;
    });

    // Apply translations on load
    applyTranslations(savedLang);
});

window.setLanguage = function(langCode) {
    console.log("Setting native language to:", langCode);
    localStorage.setItem("siteLang", langCode);
    
    // Sync all dropdowns on page
    document.querySelectorAll('.lang-selector').forEach(sel => {
        sel.value = langCode;
    });

    applyTranslations(langCode);
};

function applyTranslations(langCode) {
    const dict = translations[langCode] || translations["en"];
    
    // Find all elements with a data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else {
                el.innerText = dict[key];
            }
        }
    });
}

// Global helper used by app.js
window.getTranslation = function(lang, key) {
    const dict = translations[lang] || translations['en'];
    return (dict && dict[key]) ? dict[key] : key;
};

// Also expose currentGlobalLang for app.js compatibility
if (typeof window.currentGlobalLang === 'undefined') {
    window.currentGlobalLang = localStorage.getItem('siteLang') || 'en';
}
